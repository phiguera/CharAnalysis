# ---- Jitter functions ------------------------------------------------

# Beeswarm: returns y-offsets in cal yr BP units (same scale as x-axis).
# radius_yr:  radius of a prob = 1 circle in years; tune to match figure size.
# step_yr:    y-step between jitter levels; default = 90% of radius_yr.
beeswarm_y <- function(ages, probs, radius_yr = 180, step_yr = NULL) {
  if (is.null(step_yr)) step_yr <- radius_yr * 0.90
  n   <- length(ages)
  y   <- rep(0, n)
  cx  <- numeric(0); cy_placed <- numeric(0); r_placed <- numeric(0)
  for (i in seq_len(n)) {
    ri   <- radius_yr * probs[i]
    best <- 0L; found <- FALSE
    for (m in 0:12) {
      cands <- if (m == 0L) 0 else c(m * step_yr, -m * step_yr)
      for (cy in cands) {
        ok <- TRUE
        if (length(cx) > 0L) {
          dx  <- ages[i] - cx
          dyi <- cy - cy_placed
          rj  <- r_placed
          if (any(sqrt(dx^2 + dyi^2) < (ri + rj) * 1.05)) ok <- FALSE
        }
        if (ok) { best <- cy; found <- TRUE; break }
      }
      if (found) break
    }
    y[i] <- best
    cx          <- c(cx, ages[i])
    cy_placed   <- c(cy_placed, best)
    r_placed    <- c(r_placed, ri)
  }
  y
}

# Bar jitter: returns y-offsets in cal yr BP units.
# ci_lo / ci_hi:  CI bounds (any units consistent with ages).
# step_yr:        vertical spacing between non-overlapping bar rows.
bar_y <- function(ci_lo, ci_hi, step_yr = 45) {
  n  <- length(ci_lo)
  y  <- rep(0, n)
  xl_p <- numeric(0); xr_p <- numeric(0); cy_p <- numeric(0)
  for (i in seq_len(n)) {
    best <- 0; found <- FALSE
    for (m in 0:15) {
      cands <- if (m == 0L) 0 else c(m * step_yr, -m * step_yr)
      for (cy in cands) {
        ok <- TRUE
        if (length(xl_p) > 0L) {
          x_ovlp <- ci_lo[i] < xr_p & ci_hi[i] > xl_p
          y_close <- abs(cy - cy_p) < step_yr * 0.95
          if (any(x_ovlp & y_close)) ok <- FALSE
        }
        if (ok) { best <- cy; found <- TRUE; break }
      }
      if (found) break
    }
    y[i] <- best
    xl_p <- c(xl_p, ci_lo[i])
    xr_p <- c(xr_p, ci_hi[i])
    cy_p <- c(cy_p, best)
  }
  y
}


