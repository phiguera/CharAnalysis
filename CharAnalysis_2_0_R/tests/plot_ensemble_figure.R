# plot_ensemble_figure.R
# -----------------------------------------------------------------------
# Four-panel ensemble figure summarizing chronological uncertainty in
# peak detection for a single charcoal record.
#
# RATIONALE
# ---------
# Standard CharAnalysis runs use a single "best-estimate" age-depth model
# (typically the median of a Bayesian age model such as Bacon). This
# ignores age uncertainty: the same sediment sample may be assigned
# meaningfully different ages across the posterior ensemble of chronologies,
# which affects both (1) the accumulation-rate denominators used to compute
# CHAR and (2) the absolute dates assigned to detected peaks. The ensemble
# approach reruns the full pipeline once per chronology in an N-member
# ensemble (default N = 1000, generated by Bacon or MC_AgeDepth.m) and
# summarises two quantities per reference peak:
#
#   P(peak)      -- fraction of ensemble iterations that identify a fire
#                   event near the same time as the reference run. Reflects
#                   how robustly the peak survives across plausible
#                   chronologies; values < ~0.7 suggest the event may be
#                   an artifact of the single best-estimate chronology.
#
#   Timing CI    -- 95% confidence interval on the detected age of each
#                   reference peak across the ensemble. Reflects how much
#                   chronological uncertainty translates into uncertainty
#                   in the absolute timing of a fire event.
#
# PANEL DESCRIPTIONS AND METHODS
# --------------------------------
# Panel (a) — CHAR time series
#   Replicates char_plot_sni() panel (a): interpolated charcoal
#   accumulation rate (CHAR), background curve, and positive/negative
#   thresholds from the reference (single-chronology) run. Peak
#   identifications from the reference run are shown as crosses.
#
# Panel (b) — Signal-to-noise index (SNI)
#   SNI time series from the reference run; dashed line at SNI = 3.0
#   (Kelly et al. 2011 threshold for reliable peak detection).
#
# Panel (c) — P(peak) beeswarm
#   One circle per reference peak; x = reference peak age; circle size
#   scaled to P(peak) using a fixed 5-bin scale (0–20, 21–40, 41–60,
#   61–80, 81–100%) so the encoding is consistent across records.
#
#   Matching algorithm (run_ensemble_analysis.R):
#     For each reference peak k (k = 1 … n_peaks) and each ensemble
#     iteration i (i = 1 … N):
#       1. Find all time steps with peaks_matrix[t, i] == 1.
#       2. Identify the single closest detected age to the reference
#          peak age.
#       3. If that distance ≤ half-window, assign the detected age to
#          peak k for iteration i.
#     The half-window = max(mean_mFRI / 2, yrInterp), where mean_mFRI
#     is the Weibull mean fire-return interval averaged across zones
#     (from out$post$FRI_params_zone[, 2]).  The reference-peak-first
#     loop guarantees at most one detection per reference peak per
#     iteration, so P(peak) = n_detected / N ≤ 1.0.
#
#   Beeswarm jitter: circles are offset in y (cal yr BP units) using a
#   greedy placement algorithm (beeswarm_y()) that prevents overlap
#   based on Euclidean distance in (age, y) space. Bin midpoints (0.10,
#   0.30, …, 0.90) are used as the jitter radius, not raw probabilities,
#   so spacing is consistent across records regardless of the observed
#   probability range.
#
# Panel (d) — 95% CI on peak timing
#   One horizontal bar per reference peak; x-extent = [2.5th, 97.5th
#   percentile] of detected ages across the N ensemble iterations; dot
#   at the reference peak age. For closely spaced peaks, bars are
#   offset in y using bar_y() (x-range overlap + y-proximity check)
#   to prevent overlap.
#
